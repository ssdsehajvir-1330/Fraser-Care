
-- FraserCare database schema

CREATE TABLE IF NOT EXISTS pharmacy_services (
    service_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(255) NOT NULL UNIQUE,
    description VARCHAR(255),
    duration_minutes INTEGER NOT NULL,
    active BOOLEAN NOT NULL DEFAULT TRUE
);

-- Initial pharmacy services

INSERT INTO pharmacy_services
    (name, description, duration_minutes, active)
VALUES
    ('Flu Vaccination', 'Seasonal influenza vaccination', 15, TRUE),
    ('Medication Review', 'Review of current medications', 30, TRUE),
    ('Blood Pressure Check', 'Blood pressure measurement', 15, TRUE)
ON CONFLICT (name) DO NOTHING;

-- Appointment bookings

CREATE TABLE IF NOT EXISTS appointments (
    appointment_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id BIGINT NOT NULL,
    service_id BIGINT NOT NULL REFERENCES pharmacy_services(service_id),
    appointment_date DATE NOT NULL,
    start_time TIME NOT NULL,
    end_time TIME NOT NULL,
    status VARCHAR(255) NOT NULL DEFAULT 'BOOKED',
    CHECK (end_time > start_time)
);

-- Authentication users

CREATE TABLE IF NOT EXISTS auth_users (
    username VARCHAR(255) PRIMARY KEY,
    password VARCHAR(255) NOT NULL,
    enabled BOOLEAN NOT NULL DEFAULT TRUE,
    full_name VARCHAR(255)
);

-- Authentication authorities (roles)

CREATE TABLE IF NOT EXISTS auth_authorities (
    username VARCHAR(255) NOT NULL REFERENCES auth_users(username)
        ON DELETE CASCADE,
    authority VARCHAR(50) NOT NULL,
    PRIMARY KEY (username, authority)
);
